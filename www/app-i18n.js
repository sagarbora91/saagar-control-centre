  function validLanguage(lang){ return lang==='mr'||lang==='hi'||lang==='en'; }
  function readLanguage(){
    try{ var value=root.localStorage.getItem(LANGUAGE_KEY); if(validLanguage(value)) return value; }catch(e){}
    return 'en';
  }
  function translate(text,lang){
    text=String(text==null?'':text);
    lang=validLanguage(lang)?lang:'en';
    if(lang==='en') return text;
    var match=text.match(/^(\s*[^A-Za-z0-9]*)(.*?)(\s*)$/);
    var prefix=match?match[1]:'';
    var core=match?match[2]:text;
    var suffix=match?match[3]:'';
    var translated=dictionaries[lang][core];
    if(translated==null && /:$/.test(core)){
      var withoutColon=core.slice(0,-1).trimEnd();
      if(dictionaries[lang][withoutColon]!=null) translated=dictionaries[lang][withoutColon]+':';
    }
    if(translated==null){
      var decorated=core.match(/^(.*?)(\s*(?:\*|…|→|✓|✗|\d+))$/);
      if(decorated&&decorated[1]&&dictionaries[lang][decorated[1]]!=null) translated=dictionaries[lang][decorated[1]]+decorated[2];
    }
    if(translated==null){
      var pinSummary=core.match(/^Owner PIN (set|not set) - (\d+) protected$/);
      if(pinSummary) translated=(pinSummary[1]==='set'?(lang==='mr'?'मालक पिन सेट आहे':'मालिक पिन सेट है'):(lang==='mr'?'मालक पिन सेट नाही':'मालिक पिन सेट नहीं है'))+' - '+pinSummary[2]+' '+(lang==='mr'?'संरक्षित':'सुरक्षित');
      var syncSummary=core.match(/^Last sync (.+)$/);
      if(syncSummary) translated=(lang==='mr'?'शेवटचे समक्रमण ':'अंतिम सिंक ')+syncSummary[1];
      var startupSummary=core.match(/^(\d+) startup issue\(s\)$/);
      if(startupSummary) translated=startupSummary[1]+' '+(lang==='mr'?'सुरुवातीच्या समस्या':'स्टार्टअप समस्याएँ');
    }
    if(translated==null){
      var pieces=core.split(/(\s+(?:-|·)\s+|\s+|[\/&–—])/);
      var output='',changed=false,valid=true;
      for(var p=0;p<pieces.length;p++){
        var piece=pieces[p];
        if(/^[A-Za-z][A-Za-z'’.-]*$/.test(piece)){
          var word=wordMaps[lang][piece.toLowerCase()];
          if(word!=null){ output+=word; changed=true; }
          else if(/^[A-Z]{2,6}$/.test(piece)){ output+=piece; }
          else { valid=false; break; }
        }else output+=piece;
      }
      if(valid&&changed) translated=output;
    }
    return translated==null?text:(prefix+translated+suffix);
  }
  function blocked(element){
    if(!element||!element.closest) return true;
    if(element.closest('[contenteditable="true"],[data-no-i18n],[data-i18n]')) return true;
    return !!(element.closest('TBODY')&&!element.closest('button,[role="button"],[data-i18n-ui]'));
  }
  function localizeTextNode(node,lang){
    if(!node||node.nodeType!==3||blocked(node.parentElement)||/^(INPUT|TEXTAREA)$/.test(node.parentElement&&node.parentElement.tagName||'')) return;
    var current=String(node.nodeValue||'');
    if(!current.trim()) return;
    var state=node.__saagarI18nState;
    if(!state){ state=node.__saagarI18nState={en:current,rendered:current}; }
    else if(current!==state.rendered && current!==state.en){ state.en=current; }
    var next=translate(state.en,lang);
    state.rendered=next;
    if(current!==next) node.nodeValue=next;
  }
  function walkText(element,lang){
    if(!element||blocked(element)) return;
    var children=element.childNodes||[];
    for(var i=0;i<children.length;i++){
      if(children[i].nodeType===3) localizeTextNode(children[i],lang);
      else if(children[i].nodeType===1) walkText(children[i],lang);
    }
  }
  function localizeAttribute(element,name,lang){
    if(!element||blocked(element)||!element.hasAttribute||!element.hasAttribute(name)) return;
    var key='__saagarI18nAttr_'+name.replace(/-/g,'_');
    var current=element.getAttribute(name)||'';
    var state=element[key];
    if(!state){ state=element[key]={en:current,rendered:current}; }
    else if(current!==state.rendered && current!==state.en){ state.en=current; }
    var next=translate(state.en,lang);
    state.rendered=next;
    if(current!==next) element.setAttribute(name,next);
  }
  function apply(lang){
    lang=validLanguage(lang)?lang:readLanguage();
    try{ document.documentElement.lang=lang; }catch(e){}
    var elements=[];
    try{ elements=document.querySelectorAll(UI_SELECTOR); }catch(e){}
    for(var i=0;i<elements.length;i++) walkText(elements[i],lang);
    var attributed=[];
    try{ attributed=document.querySelectorAll('[placeholder],[title],[aria-label]'); }catch(e){}
    for(var j=0;j<attributed.length;j++){
      localizeAttribute(attributed[j],'placeholder',lang);
      localizeAttribute(attributed[j],'title',lang);
      localizeAttribute(attributed[j],'aria-label',lang);
    }
    return lang;
  }
  function setLanguage(lang){
    if(!validLanguage(lang)) return readLanguage();
    try{ root.localStorage.setItem(LANGUAGE_KEY,lang); }catch(e){}
    return apply(lang);
  }
  var timer=0;
  function schedule(){
    try{ root.clearTimeout(timer); timer=root.setTimeout(function(){ apply(readLanguage()); },40); }
    catch(e){ apply(readLanguage()); }
  }
  function boot(){
    apply(readLanguage());
    try{ new MutationObserver(schedule).observe(document.body||document.documentElement,{subtree:true,childList:true,characterData:true,attributes:true,attributeFilter:['placeholder','title','aria-label']}); }catch(e){}
  }

